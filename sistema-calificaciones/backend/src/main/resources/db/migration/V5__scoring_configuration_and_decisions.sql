ALTER TABLE resultados ADD CONSTRAINT uq_resultados_id_evaluacion UNIQUE (id, evaluacion_id);

CREATE TABLE decisiones_resultado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL,
    resultado_id bigint NOT NULL,
    politica_id bigint NOT NULL,
    posicion integer,
    aprobado boolean,
    cupo_aplicado integer,
    minima_aplicada numeric(12,4),
    registrada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_decisiones_resultado FOREIGN KEY (resultado_id, evaluacion_id)
        REFERENCES resultados(id, evaluacion_id),
    CONSTRAINT fk_decisiones_politica FOREIGN KEY (politica_id, evaluacion_id)
        REFERENCES politicas_resultado(id, evaluacion_id)
);
CREATE INDEX ix_decisiones_resultado_historial ON decisiones_resultado (resultado_id, id DESC);
