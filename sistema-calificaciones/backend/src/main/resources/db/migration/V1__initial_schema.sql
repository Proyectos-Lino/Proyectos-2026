-- Modelo nuevo. No importa ni transforma datos del sistema de admisión anterior.
-- Las claves compuestas impiden relacionar registros de organizaciones o evaluaciones distintas.

CREATE TABLE organizaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(40) NOT NULL UNIQUE,
    nombre varchar(180) NOT NULL,
    activa boolean NOT NULL DEFAULT true,
    creada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_organizaciones_codigo CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_organizaciones_nombre CHECK (length(trim(nombre)) > 0)
);

CREATE TABLE usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    nombre varchar(160) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuarios_correo CHECK (length(trim(correo)) > 0),
    CONSTRAINT ck_usuarios_password CHECK (length(trim(password_hash)) > 0),
    CONSTRAINT ck_usuarios_nombre CHECK (length(trim(nombre)) > 0)
);
CREATE UNIQUE INDEX ux_usuarios_correo_normalizado ON usuarios (lower(trim(correo)));

CREATE TABLE membresias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizaciones(id),
    usuario_id bigint NOT NULL REFERENCES usuarios(id),
    rol varchar(30) NOT NULL,
    activa boolean NOT NULL DEFAULT true,
    creada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_membresias_organizacion_usuario UNIQUE (organizacion_id, usuario_id),
    CONSTRAINT ck_membresias_rol CHECK (rol IN ('ADMINISTRADOR', 'OPERADOR', 'REVISOR', 'LECTOR'))
);
CREATE INDEX ix_membresias_usuario ON membresias (usuario_id);

CREATE TABLE evaluaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizaciones(id),
    codigo varchar(60) NOT NULL,
    nombre varchar(180) NOT NULL,
    descripcion text,
    tipo varchar(40) NOT NULL DEFAULT 'GENERAL',
    estado varchar(20) NOT NULL DEFAULT 'BORRADOR',
    fecha_evaluacion date,
    creada_en timestamptz NOT NULL DEFAULT now(),
    actualizada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_evaluaciones_codigo UNIQUE (organizacion_id, codigo),
    CONSTRAINT uq_evaluaciones_id_organizacion UNIQUE (id, organizacion_id),
    CONSTRAINT ck_evaluaciones_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_evaluaciones_codigo CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_evaluaciones_tipo CHECK (length(trim(tipo)) > 0),
    CONSTRAINT ck_evaluaciones_estado CHECK (estado IN ('BORRADOR', 'CONFIGURADA', 'EN_PROCESO', 'CERRADA', 'PUBLICADA', 'ARCHIVADA'))
);
CREATE INDEX ix_evaluaciones_organizacion_estado ON evaluaciones (organizacion_id, estado, creada_en DESC);

CREATE TABLE grupos_evaluacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    codigo varchar(60) NOT NULL,
    nombre varchar(180) NOT NULL,
    cupo integer,
    CONSTRAINT uq_grupos_evaluacion_codigo UNIQUE (evaluacion_id, codigo),
    CONSTRAINT uq_grupos_evaluacion_id UNIQUE (id, evaluacion_id),
    CONSTRAINT ck_grupos_evaluacion_codigo CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_grupos_evaluacion_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_grupos_evaluacion_cupo CHECK (cupo IS NULL OR cupo >= 0)
);

CREATE TABLE participantes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizaciones(id),
    codigo varchar(80) NOT NULL,
    nombres varchar(160) NOT NULL,
    apellidos varchar(160),
    documento varchar(40),
    correo varchar(254),
    creado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_participantes_codigo UNIQUE (organizacion_id, codigo),
    CONSTRAINT uq_participantes_id_organizacion UNIQUE (id, organizacion_id),
    CONSTRAINT ck_participantes_codigo CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_participantes_nombres CHECK (length(trim(nombres)) > 0)
);
CREATE INDEX ix_participantes_organizacion_documento ON participantes (organizacion_id, documento);

CREATE TABLE inscripciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL,
    evaluacion_id bigint NOT NULL,
    participante_id bigint NOT NULL,
    grupo_id bigint,
    codigo_externo varchar(80),
    inscrita_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_inscripciones_evaluacion FOREIGN KEY (evaluacion_id, organizacion_id)
        REFERENCES evaluaciones(id, organizacion_id),
    CONSTRAINT fk_inscripciones_participante FOREIGN KEY (participante_id, organizacion_id)
        REFERENCES participantes(id, organizacion_id),
    CONSTRAINT fk_inscripciones_grupo FOREIGN KEY (grupo_id, evaluacion_id)
        REFERENCES grupos_evaluacion(id, evaluacion_id),
    CONSTRAINT uq_inscripciones_participante UNIQUE (evaluacion_id, participante_id),
    CONSTRAINT uq_inscripciones_id_evaluacion UNIQUE (id, evaluacion_id)
);
CREATE INDEX ix_inscripciones_evaluacion_grupo ON inscripciones (evaluacion_id, grupo_id);
CREATE INDEX ix_inscripciones_participante ON inscripciones (participante_id);

CREATE TABLE formularios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    codigo varchar(60) NOT NULL,
    nombre varchar(120),
    numero_preguntas integer NOT NULL,
    opciones_por_pregunta integer NOT NULL DEFAULT 5,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_formularios_codigo UNIQUE (evaluacion_id, codigo),
    CONSTRAINT uq_formularios_id_evaluacion UNIQUE (id, evaluacion_id),
    CONSTRAINT ck_formularios_codigo CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_formularios_numero_preguntas CHECK (numero_preguntas > 0),
    CONSTRAINT ck_formularios_opciones CHECK (opciones_por_pregunta BETWEEN 2 AND 26)
);

CREATE TABLE claves_respuesta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formulario_id bigint NOT NULL REFERENCES formularios(id),
    version integer NOT NULL,
    respuestas jsonb NOT NULL,
    creada_en timestamptz NOT NULL DEFAULT now(),
    creada_por bigint REFERENCES usuarios(id),
    CONSTRAINT uq_claves_respuesta_version UNIQUE (formulario_id, version),
    CONSTRAINT uq_claves_respuesta_id_formulario UNIQUE (id, formulario_id),
    CONSTRAINT ck_claves_respuesta_version CHECK (version > 0),
    CONSTRAINT ck_claves_respuesta_json CHECK (jsonb_typeof(respuestas) = 'array')
);

CREATE TABLE reglas_calificacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    version integer NOT NULL,
    puntos_correcta numeric(12,4) NOT NULL,
    puntos_incorrecta numeric(12,4) NOT NULL DEFAULT 0,
    puntos_blanca numeric(12,4) NOT NULL DEFAULT 0,
    minima_aprobacion numeric(12,4),
    creada_en timestamptz NOT NULL DEFAULT now(),
    creada_por bigint REFERENCES usuarios(id),
    CONSTRAINT uq_reglas_calificacion_version UNIQUE (evaluacion_id, version),
    CONSTRAINT uq_reglas_calificacion_id_evaluacion UNIQUE (id, evaluacion_id),
    CONSTRAINT ck_reglas_calificacion_version CHECK (version > 0),
    CONSTRAINT ck_reglas_calificacion_correcta CHECK (puntos_correcta >= 0)
);

CREATE TABLE lotes_importacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    nombre_archivo varchar(255) NOT NULL,
    hash_sha256 char(64),
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE',
    total_registros integer NOT NULL DEFAULT 0,
    registros_validos integer NOT NULL DEFAULT 0,
    registros_error integer NOT NULL DEFAULT 0,
    mensaje_error text,
    creado_en timestamptz NOT NULL DEFAULT now(),
    terminado_en timestamptz,
    creado_por bigint REFERENCES usuarios(id),
    CONSTRAINT uq_lotes_importacion_id_evaluacion UNIQUE (id, evaluacion_id),
    CONSTRAINT ck_lotes_importacion_estado CHECK (estado IN ('PENDIENTE', 'PROCESANDO', 'COMPLETADO', 'COMPLETADO_CON_ERRORES', 'FALLIDO')),
    CONSTRAINT ck_lotes_importacion_conteos CHECK (total_registros >= 0 AND registros_validos >= 0 AND registros_error >= 0),
    CONSTRAINT ck_lotes_importacion_nombre CHECK (length(trim(nombre_archivo)) > 0)
);
CREATE INDEX ix_lotes_importacion_evaluacion_fecha ON lotes_importacion (evaluacion_id, creado_en DESC);

CREATE TABLE hojas_respuesta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    inscripcion_id bigint NOT NULL,
    formulario_id bigint NOT NULL,
    lote_id bigint,
    codigo_hoja varchar(80),
    respuestas jsonb NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'RECIBIDA',
    observacion text,
    creada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_hojas_respuesta_inscripcion FOREIGN KEY (inscripcion_id, evaluacion_id)
        REFERENCES inscripciones(id, evaluacion_id),
    CONSTRAINT fk_hojas_respuesta_formulario FOREIGN KEY (formulario_id, evaluacion_id)
        REFERENCES formularios(id, evaluacion_id),
    CONSTRAINT fk_hojas_respuesta_lote FOREIGN KEY (lote_id, evaluacion_id)
        REFERENCES lotes_importacion(id, evaluacion_id),
    CONSTRAINT uq_hojas_respuesta_inscripcion UNIQUE (inscripcion_id),
    CONSTRAINT uq_hojas_respuesta_id_contexto UNIQUE (id, formulario_id, evaluacion_id),
    CONSTRAINT ck_hojas_respuesta_json CHECK (jsonb_typeof(respuestas) = 'array'),
    CONSTRAINT ck_hojas_respuesta_estado CHECK (estado IN ('RECIBIDA', 'OBSERVADA', 'VALIDADA', 'ANULADA'))
);
CREATE UNIQUE INDEX ux_hojas_respuesta_codigo ON hojas_respuesta (evaluacion_id, codigo_hoja)
    WHERE codigo_hoja IS NOT NULL;
CREATE INDEX ix_hojas_respuesta_evaluacion_estado ON hojas_respuesta (evaluacion_id, estado, id);
CREATE INDEX ix_hojas_respuesta_lote ON hojas_respuesta (lote_id);

CREATE TABLE resultados (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL,
    hoja_id bigint NOT NULL,
    formulario_id bigint NOT NULL,
    clave_id bigint NOT NULL,
    regla_id bigint NOT NULL,
    correctas integer NOT NULL,
    incorrectas integer NOT NULL,
    blancas integer NOT NULL,
    puntaje numeric(14,4) NOT NULL,
    posicion integer,
    aprobado boolean,
    calculado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_resultados_hoja FOREIGN KEY (hoja_id, formulario_id, evaluacion_id)
        REFERENCES hojas_respuesta(id, formulario_id, evaluacion_id),
    CONSTRAINT fk_resultados_clave FOREIGN KEY (clave_id, formulario_id)
        REFERENCES claves_respuesta(id, formulario_id),
    CONSTRAINT fk_resultados_regla FOREIGN KEY (regla_id, evaluacion_id)
        REFERENCES reglas_calificacion(id, evaluacion_id),
    CONSTRAINT uq_resultados_hoja UNIQUE (hoja_id),
    CONSTRAINT ck_resultados_conteos CHECK (correctas >= 0 AND incorrectas >= 0 AND blancas >= 0),
    CONSTRAINT ck_resultados_posicion CHECK (posicion IS NULL OR posicion > 0)
);
CREATE INDEX ix_resultados_ranking ON resultados (evaluacion_id, puntaje DESC, id);

CREATE TABLE revisiones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hoja_id bigint NOT NULL REFERENCES hojas_respuesta(id),
    estado varchar(20) NOT NULL DEFAULT 'ABIERTA',
    motivo text NOT NULL,
    resolucion text,
    abierta_por bigint REFERENCES usuarios(id),
    resuelta_por bigint REFERENCES usuarios(id),
    abierta_en timestamptz NOT NULL DEFAULT now(),
    resuelta_en timestamptz,
    CONSTRAINT ck_revisiones_estado CHECK (estado IN ('ABIERTA', 'APROBADA', 'RECHAZADA', 'ANULADA')),
    CONSTRAINT ck_revisiones_motivo CHECK (length(trim(motivo)) > 0),
    CONSTRAINT ck_revisiones_resolucion CHECK (estado = 'ABIERTA' OR (resolucion IS NOT NULL AND resuelta_en IS NOT NULL))
);
CREATE INDEX ix_revisiones_hoja_fecha ON revisiones (hoja_id, abierta_en DESC);
CREATE UNIQUE INDEX ux_revisiones_abierta_por_hoja ON revisiones (hoja_id) WHERE estado = 'ABIERTA';

CREATE TABLE evidencias_revision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id bigint NOT NULL REFERENCES revisiones(id),
    nombre_original varchar(255) NOT NULL,
    ruta_almacenamiento varchar(1000) NOT NULL,
    tipo_contenido varchar(120),
    tamanio_bytes bigint NOT NULL,
    subida_por bigint REFERENCES usuarios(id),
    subida_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_evidencias_revision_tamanio CHECK (tamanio_bytes > 0),
    CONSTRAINT ck_evidencias_revision_ruta CHECK (length(trim(ruta_almacenamiento)) > 0)
);
CREATE INDEX ix_evidencias_revision_revision ON evidencias_revision (revision_id);

CREATE TABLE eventos_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id bigint NOT NULL REFERENCES organizaciones(id),
    usuario_id bigint REFERENCES usuarios(id),
    evaluacion_id bigint,
    accion varchar(80) NOT NULL,
    entidad varchar(80) NOT NULL,
    entidad_id bigint,
    detalles jsonb NOT NULL DEFAULT '{}'::jsonb,
    ocurrido_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_eventos_auditoria_evaluacion FOREIGN KEY (evaluacion_id, organizacion_id)
        REFERENCES evaluaciones(id, organizacion_id),
    CONSTRAINT ck_eventos_auditoria_detalles CHECK (jsonb_typeof(detalles) = 'object'),
    CONSTRAINT ck_eventos_auditoria_accion CHECK (length(trim(accion)) > 0)
);
CREATE INDEX ix_eventos_auditoria_organizacion_fecha ON eventos_auditoria (organizacion_id, ocurrido_en DESC);
CREATE INDEX ix_eventos_auditoria_evaluacion_fecha ON eventos_auditoria (evaluacion_id, ocurrido_en DESC);
