CREATE TABLE versiones_resultado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resultado_id bigint NOT NULL REFERENCES resultados(id),
    version integer NOT NULL,
    clave_id bigint NOT NULL REFERENCES claves_respuesta(id),
    regla_id bigint NOT NULL REFERENCES reglas_calificacion(id),
    configuracion_seccion_id bigint REFERENCES configuraciones_seccion(id),
    detalle_secciones jsonb NOT NULL DEFAULT '[]'::jsonb,
    correctas integer NOT NULL,
    incorrectas integer NOT NULL,
    blancas integer NOT NULL,
    puntaje numeric(14,4) NOT NULL,
    motivo text NOT NULL,
    calculada_por bigint REFERENCES usuarios(id),
    calculada_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_versiones_resultado UNIQUE (resultado_id, version),
    CONSTRAINT ck_versiones_resultado_motivo CHECK (length(trim(motivo)) > 0)
);
CREATE INDEX ix_versiones_resultado_resultado ON versiones_resultado (resultado_id, version DESC);

