CREATE TABLE configuraciones_seccion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formulario_id bigint NOT NULL REFERENCES formularios(id),
    version integer NOT NULL,
    creada_en timestamptz NOT NULL DEFAULT now(),
    creada_por bigint REFERENCES usuarios(id),
    CONSTRAINT uq_configuraciones_seccion_version UNIQUE (formulario_id, version),
    CONSTRAINT uq_configuraciones_seccion_id_formulario UNIQUE (id, formulario_id)
);
CREATE TABLE secciones_configuracion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configuracion_id bigint NOT NULL REFERENCES configuraciones_seccion(id),
    orden integer NOT NULL,
    codigo varchar(40) NOT NULL,
    nombre varchar(120) NOT NULL,
    pregunta_desde integer NOT NULL,
    pregunta_hasta integer NOT NULL,
    puntos_correcta numeric(12,4) NOT NULL,
    puntos_incorrecta numeric(12,4) NOT NULL,
    puntos_blanca numeric(12,4) NOT NULL,
    CONSTRAINT uq_secciones_orden UNIQUE (configuracion_id, orden),
    CONSTRAINT uq_secciones_codigo UNIQUE (configuracion_id, codigo),
    CONSTRAINT ck_secciones_rango CHECK (pregunta_desde >= 1 AND pregunta_hasta >= pregunta_desde),
    CONSTRAINT ck_secciones_nombre CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_secciones_correcta CHECK (puntos_correcta >= 0)
);

