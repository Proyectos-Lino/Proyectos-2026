-- Las versiones son inmutables; resultados y decisiones conservan la configuración aplicada.
CREATE TABLE politicas_resultado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluacion_id bigint NOT NULL REFERENCES evaluaciones(id),
    version integer NOT NULL,
    alcance_ranking varchar(10) NOT NULL,
    modo_aprobacion varchar(24) NOT NULL,
    desempate varchar(24) NOT NULL,
    cupo_global integer,
    creada_en timestamptz NOT NULL DEFAULT now(),
    creada_por bigint REFERENCES usuarios(id),
    CONSTRAINT uq_politicas_resultado_version UNIQUE (evaluacion_id, version),
    CONSTRAINT uq_politicas_resultado_id_evaluacion UNIQUE (id, evaluacion_id),
    CONSTRAINT ck_politicas_alcance CHECK (alcance_ranking IN ('GLOBAL', 'GRUPO')),
    CONSTRAINT ck_politicas_modo CHECK (modo_aprobacion IN ('NINGUNA', 'MINIMA', 'VACANTES', 'AMBAS', 'VACANTES_O_MINIMA')),
    CONSTRAINT ck_politicas_desempate CHECK (desempate IN ('COMPARTIR_PUESTO', 'CORRECTAS', 'MENOS_INCORRECTAS', 'CODIGO')),
    CONSTRAINT ck_politicas_cupo CHECK (cupo_global IS NULL OR cupo_global >= 0)
);
CREATE INDEX ix_politicas_resultado_actual ON politicas_resultado (evaluacion_id, version DESC);

-- Equivale a la regla histórica: vacantes por grupo cuando existen; en otro caso nota mínima.
