CREATE TABLE configuraciones_publicacion (
    evaluacion_id bigint PRIMARY KEY REFERENCES evaluaciones(id),
    mostrar_puntaje boolean NOT NULL DEFAULT true,
    mostrar_puesto boolean NOT NULL DEFAULT false,
    mostrar_aprobacion boolean NOT NULL DEFAULT true,
    mostrar_conteos boolean NOT NULL DEFAULT false,
    visible_desde timestamptz,
    visible_hasta timestamptz,
    aprobada_por bigint REFERENCES usuarios(id),
    aprobada_en timestamptz,
    publicada_por bigint REFERENCES usuarios(id),
    publicada_en timestamptz,
    CONSTRAINT ck_publicacion_periodo CHECK (visible_hasta IS NULL OR visible_desde IS NULL OR visible_hasta > visible_desde)
);

CREATE TABLE accesos_resultado (
    inscripcion_id bigint PRIMARY KEY REFERENCES inscripciones(id),
    token_hash char(64) NOT NULL UNIQUE,
    generado_por bigint NOT NULL REFERENCES usuarios(id),
    generado_en timestamptz NOT NULL DEFAULT now(),
    revocado_en timestamptz
);
CREATE INDEX ix_accesos_resultado_hash ON accesos_resultado (token_hash) WHERE revocado_en IS NULL;
